#!/usr/bin/env python3
"""Сверяет сертификат, выданный инструментом, с эталонным PDF — построчно.

Так выверялась раскладка: для каждой строки меряется реальная «коробка чернил»
и сравнивается с эталоном. Δширины — это про кегль и трекинг, Δверха — про
базовую линию. Норма: до ±4 pt по ширине (это 0,5% длины строки — остаток
разницы в кернинге, одной константой не убирается, правка трекинга только
перекидывает ошибку на соседние строки) и до ±0,6 pt по вертикали.

Запуск:  python3 calibrate.py эталон.pdf выданный.pdf
Эталон — «Сертификат SmileClinic.pdf» (N005, Сергей, 5 000₽, до 01.12.2026,
часы до 22:00). Тот же набор надо ввести в инструмент, иначе сравнивать нечего.

Если строка поехала: правь соответствующее поле в объекте L в src/tool.tpl.html
(колонка «константа»), пересобирай build.py и гоняй скрипт заново.
Нужен pymupdf и Pillow.
"""
import sys
import fitz
from PIL import Image

S = 4  # во сколько раз рендерим для замера

# полоса поиска по вертикали → какая константа за неё отвечает
LINES = [
    ("текст, строка 1", (575, 625),  "L.body (кегль 40, трекинг −0,2, centerY 703)"),
    ("текст, строка 2", (633, 683),  "L.body.lh = 58"),
    ("текст, строка 3", (691, 741),  "L.body.lh = 58"),
    ("текст, строка 4", (749, 799),  "L.body.lh = 58"),
    ("номер",           (886, 940),  "L.accent.y1 = 927,75"),
    ("номинал",         (944, 996),  "L.accent.y2 = 985,75"),
    ("срок действия",   (1092, 1130),"L.srok.y = 1119,5"),
    ("режим работы 1",  (1180, 1215),"L.hours.y1 = 1206,75"),
    ("режим работы 2",  (1218, 1252),"L.hours.y2 = 1242,25"),
    ("призыв 1",        (1282, 1315),"L.cta.y1 = 1306,75"),
    ("призыв 2",        (1318, 1350),"L.cta.y2 = 1341,75"),
    ("телефон",         (1352, 1388),"L.phone.y = 1376,75"),
]


def boxes(path):
    page = fitz.open(path)[0]
    pm = page.get_pixmap(dpi=72 * S)
    px = Image.frombytes("RGB", (pm.width, pm.height), pm.samples).load()
    out = {}
    for name, (y0, y1), _ in LINES:
        xmin, xmax, ymin = 10**9, -1, 10**9
        for y in range(y0 * S, y1 * S):
            for x in range(pm.width):
                if sum(px[x, y]) > 200:            # белый текст на тёмном фоне
                    xmin = min(xmin, x); xmax = max(xmax, x); ymin = min(ymin, y)
        out[name] = None if xmax < 0 else (xmin / S, xmax / S, ymin / S)
    return out


def main(ref, new):
    A, B = boxes(ref), boxes(new)
    print(f"{'строка':16s} {'Δширины':>9s} {'Δверха':>8s}   константа")
    плохо = 0
    for name, _, конст in LINES:
        a, b = A[name], B[name]
        if not a or not b:
            print(f"{name:16s} {'—':>9s} {'—':>8s}   "
                  f"{'нет в эталоне' if not a else 'нет в выданном'}")
            continue
        dw = (b[1] - b[0]) - (a[1] - a[0])
        dy = b[2] - a[2]
        флаг = "" if abs(dw) <= 4 and abs(dy) <= 0.6 else "  ← ушло"
        плохо += bool(флаг)
        print(f"{name:16s} {dw:+9.2f} {dy:+8.2f}   {конст}{флаг}")
    print("\nвсё в допуске" if not плохо else f"\nстрок за допуском: {плохо}")


if __name__ == "__main__":
    if len(sys.argv) < 3:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2])
